// Builds components/scheduler/dark-theme.generated.css from Bryntum's dark theme, scoped so it
// applies when the system is dark (unless <html data-theme="light">) or <html data-theme="dark">.
// Run on postinstall: a plain `@import ... (prefers-color-scheme: dark)` inlines the file's
// @charset inside a media block, which the CSS parser rejects.

import { readFileSync, writeFileSync } from 'node:fs';

const source = readFileSync('node_modules/@bryntum/scheduler/svalbard-dark.css', 'utf8').replace(/@charset "[^"]*";/g, '');
const forced = source.replaceAll(':root:not(.b-nothing)', ':root[data-theme="dark"]:not(.b-nothing)');
const system = source.replaceAll(':root:not(.b-nothing)', ':root:not([data-theme="light"]):not(.b-nothing)');
writeFileSync(
  'components/scheduler/dark-theme.generated.css',
  `/* Generated by scripts/bryntum-dark-theme.mjs from @bryntum/scheduler/svalbard-dark.css. Do not edit. */\n` +
    `@media (prefers-color-scheme: dark) {\n${system}\n}\n${forced}\n`,
);
